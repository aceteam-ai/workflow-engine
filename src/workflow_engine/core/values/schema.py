class DataValueSchema(BaseValueSchema):
    """
    Matches a DataValue[T] schema, for some class T that inherits from Data.
    """

    type: Final[Literal["object"]]

    # NOTE: recursive validation does not work unless this is a dict instead of a Mapping
    properties: dict[str, ValueSchema]
    additionalProperties: ValueSchema | bool = False
    required: Sequence[str] = Field(default_factory=list)

    def build_data_cls(
        self,
        *extra_defs: Mapping[str, ValueSchema],
    ) -> type[Data]:
        """
        Rebuilds the Data type T from the schema.
        This rebuilt Data type will not be the same as the original Data type T
        (i.e. equality checks will fail), but it will have the same fields.
        It will not necessarily have the same to_value_schema() as T, because
        the rebuilding process does not yet capture all of the descriptions from
        the original schema.
        """
        # TODO: capture the descriptions from the schema
        required_set = frozenset(self.required)
        defs = (self.defs, *extra_defs)
        properties = {
            k: (
                v.to_value_cls(*defs),
                v.to_field_info(*defs, is_required=k in required_set),
            )
            for k, v in self.properties.items()
        }
        return build_data_type(name=self.title or "Data", fields=properties)

    @override
    def build_value_cls(
        self,
        *extra_defs: Mapping[str, ValueSchema],
    ) -> type[DataValue]:
        D = self.build_data_cls(*extra_defs)
        return DataValue[D]


class UnionValueSchema(BaseValueSchema):
    anyOf: Sequence[ValueSchema]

    @override
    def build_value_cls(
        self,
        *extra_defs: Mapping[str, ValueSchema],
    ) -> ValueType:
        from .union import union_value_type

        members = tuple(
            schema.to_value_cls(self.defs, *extra_defs) for schema in self.anyOf
        )
        if not members:
            raise ValueError("UnionValueSchema requires at least one anyOf member")
        return union_value_type(*members)


class ReferenceValueSchema(BaseValueSchema):
    """
    A schema of the form
    { "$defs": { "foo": ... }, "$ref": "#/$defs/foo" }
    """

    model_config: ClassVar[ConfigDict] = ConfigDict(
        serialize_by_alias=True,  # already set in BaseValueSchema, but setting again here to be explicit
    )

    ref: str = Field(
        pattern=r"^#/\$defs/\w+$",
        serialization_alias="$ref",
        validation_alias="$ref",
    )

    @model_validator(mode="before")
    @classmethod
    def rename_ref_alias(cls, data: Any) -> Any:
        """
        A Pydantic bug causes model_validate() to break when called on an
        instance of ReferenceValueSchema.
        This is because the validator receives the .ref property from the
        object, whereas it is expecting $ref.
        To fix this, we move the property to the expected key.
        """
        if isinstance(data, Mapping) and ("$ref" not in data) and ("ref" in data):
            data = dict(data)
            data["$ref"] = data.pop("ref")
            return data
        return data

    @cached_property
    def id(self) -> str:
        _hash, _defs, id = self.ref.split("/")
        assert _hash == "#"
        assert _defs == "$defs"
        return id

    @override
    def build_value_cls(
        self,
        *extra_defs: Mapping[str, ValueSchema],
    ) -> ValueType:
        for defs in (self.defs, *extra_defs):
            if self.id in defs:
                target = defs[self.id]
                key = (id(target), self.id)
                stack = _REFERENCE_STACK.get()
                if key in stack:
                    raise ValueError(
                        f"Cyclic schema reference to definition {self.id!r}; "
                        "regenerate legacy schemas with explicit x-value-type identities"
                    )
                token = _REFERENCE_STACK.set((*stack, key))
                try:
                    return target.to_value_cls(self.defs, *extra_defs)
                finally:
                    _REFERENCE_STACK.reset(token)
        raise KeyError(f"Schema definition for {self.id} not found")


_REFERENCE_STACK: ContextVar[tuple[tuple[int, str], ...]] = ContextVar(
    "value_schema_reference_stack", default=()
)


def _schema_constraints(
    schema: BaseValueSchema, *extra_defs: Mapping[str, ValueSchema]
) -> tuple[BaseValueSchema, dict[str, Any]]:
    """Read root constraints, including those behind an enum/model wrapper ref."""
    shapes = [schema]
    scopes = (schema.defs, *extra_defs)
    seen = {id(schema)}
    while isinstance(schema, ReferenceValueSchema):
        target = next((defs[schema.id] for defs in scopes if schema.id in defs), None)
        if target is None or id(target) in seen:
            break
        seen.add(id(target))
        schema = target
        shapes.append(schema)
        scopes = (schema.defs, *scopes)
    constraints = {}
    for shape in reversed(shapes):
        wire = shape.model_dump(
            mode="json", include=set(shape.model_extra or {}) | {"pattern", "enum"}
        )
        constraints.update({key: wire[key] for key in shape.model_extra or {}})
        if isinstance(shape, StringValueSchema):
            for key in ("pattern", "enum"):
                if wire.get(key) is not None:
                    constraints[key] = wire[key]
    return schema, constraints


_REGISTERED_CONSTRAINTS: dict[ValueType, tuple[BaseValueSchema, dict[str, Any]]] = {}


def _registered_constraints(
    value_cls: ValueType,
) -> tuple[BaseValueSchema, dict[str, Any]]:
    # Value classes are immutable contracts. Schema generation never consults
    # the registry, so this does not freeze it during class-definition time.
    if value_cls not in _REGISTERED_CONSTRAINTS:
        _REGISTERED_CONSTRAINTS[value_cls] = _schema_constraints(
            value_cls.to_value_schema()
        )
    return _REGISTERED_CONSTRAINTS[value_cls]


def _constraint_field_map(schema: BaseValueSchema) -> dict[str, str]:
    if isinstance(schema, (IntegerValueSchema, FloatValueSchema)):
        return _NUMERIC_FIELD_MAP
    if isinstance(schema, StringValueSchema):
        return _STRING_FIELD_MAP
    if isinstance(schema, SequenceValueSchema):
        return _SEQUENCE_FIELD_MAP
    if isinstance(schema, StringMapValueSchema):
        return _MAP_FIELD_MAP
    return {}


type ValueSchema = (
    BooleanValueSchema
    | DataValueSchema
    | DateValueSchema
    | FloatValueSchema
    | IntegerValueSchema
    | NullValueSchema
    | ResultValueSchema
    | SequenceValueSchema
    | StringMapValueSchema
    | StringValueSchema
    | UnionValueSchema
    | ReferenceValueSchema  # must be handled second-to-last
    | BaseValueSchema  # must be handled last, corresponds to the Any catch-all
)


# yep, this is possible
class ValueSchemaValue(Value[ValueSchema]):
    pass


def validate_value_schema(schema: Any) -> ValueSchema:
    # idempotent: if the schema is already a ValueSchema, just return it
    if isinstance(schema, BaseValueSchema):
        return schema
    try:
        return ValueSchemaValue.model_validate(schema).root
    except ValidationError as e:
        raise ValueError(f"Invalid value schema: {schema}") from e


class FieldSchemaMappingValue(StringMapValue[ValueSchemaValue]):
    def to_data_schema(self, title: str) -> DataValueSchema:
        return DataValueSchema(
            type="object",
            title=title,
            properties={k: v.root for k, v in self.root.items()},
            additionalProperties=False,
            required=list(self.root.keys()),
        )

    @classmethod
    def from_fields(cls, **fields: ValueType) -> Self:
        return cls(
            {
                name: ValueSchemaValue(vtype.to_value_schema())
                for name, vtype in fields.items()
            }
        )


